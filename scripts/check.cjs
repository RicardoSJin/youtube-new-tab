const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const root=path.join(__dirname,'..','extension');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8'));
assert.equal(manifest.manifest_version,3);
assert.deepEqual(manifest.permissions,['storage']);
assert.equal(manifest.host_permissions,undefined);
assert.deepEqual(manifest.content_scripts[0].matches,['https://www.youtube.com/*']);
assert.equal(manifest.content_scripts[0].run_at,'document_start');
const files=[manifest.background.service_worker,manifest.action.default_popup,manifest.options_ui.page,...manifest.content_scripts.flatMap(c=>c.js),...Object.values(manifest.icons)];
for(const file of files) assert.ok(fs.existsSync(path.join(root,file)),`Missing ${file}`);
for(const file of fs.readdirSync(root).filter(f=>f.endsWith('.js'))) new vm.Script(fs.readFileSync(path.join(root,file),'utf8'),{filename:file});
const html=fs.readFileSync(path.join(root,'settings.html'),'utf8');
for(const [,file] of html.matchAll(/(?:src|href)="([^"]+)"/g)) assert.ok(fs.existsSync(path.join(root,file)),`Missing ${file}`);
const code=fs.readdirSync(root).filter(f=>f.endsWith('.js')).map(f=>fs.readFileSync(path.join(root,f),'utf8')).join('\n');
assert.ok(!/\bfetch\s*\(|XMLHttpRequest|WebSocket|chrome\.history|tabs\.query|tabs\.update/.test(code),'Unexpected network/history/navigation API');
assert.ok(!/<script[^>]*src="https?:|\son\w+=/i.test(html),'Remote or inline script');
console.log(`Manifest ${manifest.version}: references, JavaScript syntax, permission and network checks passed.`);
